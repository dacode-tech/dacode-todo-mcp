#!/usr/bin/env python3
"""Generate a top-level index of every AGENTS.md in the tree.

Replaces "go and check whether a module has an AGENTS.md" guesswork with
one table an agent can consult first: where the file is, what it covers,
and whether it still matches the code it documents.

Fully deterministic — no model is involved, so the index can be
regenerated in a hook or CI rather than costing an agent turn.

    tools/agents-index.py             # write .agents/knowledge/INDEX.md
    tools/agents-index.py --check     # exit 1 if the index is stale
    tools/agents-index.py --stale     # list only docs lagging their code

Staleness has two independent signals:

  drift  The doc's own content changed since the index was written.
         Detected by comparing a short content hash. Cheap and exact.

  lag    The documented directory has commits *newer* than the last
         commit touching its AGENTS.md. This is the signal that actually
         matters: code moved on and the doc probably did not. It is a
         heuristic — a commit may not invalidate the doc — so it is
         reported as a count to triage, never as a hard failure.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
INDEX = REPO / ".agents/knowledge/INDEX.md"
TRIAGE = REPO / ".agents/knowledge/doc-triage.md"

# `target/` is the Cargo build directory and would cost tens of thousands of
# stats to walk; the rest are tool caches. Area docs live under docs/ and
# crates/.
SKIP_PARTS = {".agents", "node_modules", "target", "tmp", ".git", ".opencode"}
BANNER = "GENERATED by tools/agents-index.py — do not edit; re-run to refresh"


def sh(args: list[str], cwd: Path = REPO) -> str:
    try:
        r = subprocess.run(args, cwd=cwd, capture_output=True, text=True, timeout=30)
        return r.stdout.strip() if r.returncode == 0 else ""
    except (subprocess.SubprocessError, OSError):
        return ""


def discover() -> list[Path]:
    """Walk with pruning rather than rglob: the kernel checkouts under this
    root hold ~80k files each, and rglob would stat every one of them."""
    out = []
    for dirpath, dirnames, filenames in os.walk(REPO):
        dirnames[:] = [d for d in dirnames if d not in SKIP_PARTS]
        if "AGENTS.md" not in filenames:
            continue
        p = Path(dirpath) / "AGENTS.md"
        if p.stat().st_size == 0:
            continue  # 0-byte placeholder
        out.append(p.relative_to(REPO))
    return sorted(out, key=lambda p: (len(p.parts), str(p)))


def purpose(text: str) -> str:
    """Pull a one-line summary, preferring the conventional markers."""
    m = re.search(r"^>\s*\*\*Purpose\*\*:\s*(.+?)$", text, re.M)
    if not m:
        m = re.search(r"^##\s*Overview\s*\n+(?!\s*[#>|\-*])(.+?)$", text, re.M)
    if not m:
        m = re.search(r"^(?!\s*[#>|\-*`])(\S.+?)$", text, re.M)
    if not m:
        return ""
    s = re.sub(r"\s+", " ", m.group(1)).strip()
    s = re.sub(r"\*\*(.+?)\*\*", r"\1", s)
    s = re.sub(r"`(.+?)`", r"\1", s)
    if len(s) > 155:  # cut at a sentence boundary where possible
        cut = s[:155].rsplit(". ", 1)
        s = (cut[0] + ".") if len(cut) > 1 and len(cut[0]) > 60 else s[:152].rsplit(" ", 1)[0] + "…"
    return s


def topics(text: str, limit: int = 6) -> list[str]:
    seen = []
    for m in re.finditer(r"^##\s+(?!Overview\b)(.+?)\s*$", text, re.M):
        t = re.sub(r"[`*]", "", m.group(1)).strip()
        if t and t.lower() not in {"table of contents", "contents"} and t not in seen:
            seen.append(t)
    return seen[:limit]


def triage_open() -> dict[str, int]:
    """path -> count of unresolved findings recorded in doc-triage.md.

    `lag` alone is not enough: editing a doc resets it to zero even when
    only some findings were addressed, which would let a known-stale doc
    look clean. An explicit backlog cannot be reset by touching the file.
    """
    if not TRIAGE.exists():
        return {}
    counts: dict[str, int] = {}
    current = None
    for line in TRIAGE.read_text().splitlines():
        if m := re.match(r"^##\s+(\S+/AGENTS\.md)\b", line):
            current = m.group(1)
            counts.setdefault(current, 0)
        elif line.startswith("## "):
            current = None
        elif current and re.match(r"^\|\s*(high|med|low)\s*\|", line):
            counts[current] += 1
    return counts


def revision(rel: Path) -> tuple[str, int]:
    """Return (version, lag_commits)."""
    d = rel.parent
    doc_rev = sh(["git", "log", "-1", "--format=%h", "--", str(rel)])
    if not doc_rev:
        return "untracked", 0
    # The repo-root AGENTS.md documents everything, so *every* commit is a
    # commit to "its directory" and lag would count the whole history. That
    # makes the number meaningless and makes --check fail after every commit,
    # which trains people to ignore the gate. Root doc: no lag signal.
    if str(d) == ".":
        return doc_rev, 0
    # Commits to the documented directory that postdate the doc itself.
    lag = sh(["git", "rev-list", "--count", f"{doc_rev}..HEAD", "--", str(d), f":!{rel}"])
    return doc_rev, int(lag or 0)


def build() -> str:
    triage = triage_open()
    rows, total_lag, total_open = [], 0, 0
    for rel in discover():
        text = (REPO / rel).read_text(errors="replace")
        ver, lag = revision(rel)
        total_lag += 1 if lag else 0
        total_open += triage.get(str(rel), 0)
        rows.append(
            {
                "path": str(rel),
                "scope": str(rel.parent) if str(rel.parent) != "." else "(repo root)",
                "purpose": purpose(text),
                "topics": topics(text),
                "hash": hashlib.sha256(text.encode()).hexdigest()[:8],
                "ver": ver,
                "lag": lag,
                "open": triage.get(str(rel), 0),
                "lines": text.count("\n") + 1,
            }
        )

    groups = [
        ("Repository-wide", lambda r: r["path"] == "AGENTS.md"),
        ("Crates (`crates/`)", lambda r: r["path"].startswith("crates/")),
        ("Docs (`docs/`)", lambda r: r["path"].startswith("docs/")),
    ]
    used: set[str] = set()

    out = [
        f"<!-- {BANNER} -->",
        "",
        "# AGENTS.md index",
        "",
        f"{len(rows)} documentation files. **Consult the relevant entry before "
        "working in that area** — do not go looking for whether an `AGENTS.md` "
        "exists, this table is the answer.",
        "",
        "`rev` is the last commit touching the doc. `lag` counts commits to the "
        "documented directory made *since* then: a high number means the code "
        "moved on and the doc likely did not. It is a triage hint, not proof of "
        "staleness.",
        "",
    ]
    if TRIAGE.exists():
        out += [
            "`open` counts findings recorded in "
            "[`doc-triage.md`](doc-triage.md) that are still unresolved. **Read "
            "it together with `lag`** — editing a doc resets `lag` to zero even "
            "if only some findings were fixed, so a doc with `lag: —` and a "
            "non-zero `open` is still known-stale.",
            "",
        ]
    else:
        out += [
            "`open` counts unresolved findings from a documentation audit. No "
            "`doc-triage.md` backlog has been started, so every doc reads `—`; "
            "`lag` is the only staleness signal available.",
            "",
        ]
    if total_lag or total_open:
        out += [
            f"> {total_lag} of {len(rows)} docs lag their directory; "
            f"{total_open} audited findings are still open. "
            "Run `tools/agents-index.py --stale` for the lag list.",
            "",
        ]

    for title, pred in groups:
        sel = [r for r in rows if pred(r) and r["path"] not in used]
        if not sel:
            continue
        used |= {r["path"] for r in sel}
        out += [f"## {title}", "", "| Doc | Covers | rev | lag | open |", "|---|---|---|---|---|"]
        for r in sel:
            flag = f"**{r['lag']}**" if r["lag"] > 20 else (str(r["lag"]) if r["lag"] else "—")
            op = f"**{r['open']}**" if r["open"] else "—"
            out.append(
                f"| [`{r['scope']}`]({rel_link(r['path'])}) | {r['purpose']} "
                f"| `{r['ver']}` | {flag} | {op} |"
            )
        out.append("")

    rest = [r for r in rows if r["path"] not in used]
    if rest:
        out += ["## Other", "", "| Doc | Covers | rev | lag | open |", "|---|---|---|---|---|"]
        for r in rest:
            out.append(
                f"| [`{r['scope']}`]({rel_link(r['path'])}) | {r['purpose']} "
                f"| `{r['ver']}` | {r['lag'] or '—'} | {r['open'] or '—'} |"
            )
        out.append("")

    out += ["## Topics", "", "<details><summary>Section headings per doc</summary>", ""]
    for r in rows:
        if r["topics"]:
            out.append(f"- **`{r['scope']}`** — {', '.join(r['topics'])}")
    out += ["", "</details>", "", "## Integrity", "", "<!-- hashes drive --check -->", "```"]
    for r in rows:
        out.append(f"{r['hash']}  {r['ver']:<10}  {r['lines']:>5}L  {r['path']}")
    out += ["```", ""]
    return "\n".join(out)


def rel_link(path: str) -> str:
    """Link from .agents/knowledge/INDEX.md back to the repo-root path."""
    return "../../" + path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stale", action="store_true")
    args = ap.parse_args()

    if args.stale:
        found = False
        for rel in discover():
            _, lag = revision(rel)
            op = triage_open().get(str(rel), 0)
            if lag or op:
                found = True
                note = f", {op} open finding(s)" if op else ""
                print(f"{lag:>4} commits since doc{note}  {rel}")
        if not found:
            print("no docs lagging their directory")
        return 0

    content = build()
    if args.check:
        if not INDEX.exists() or INDEX.read_text() != content:
            print("AGENTS.md index is stale; run tools/agents-index.py", file=sys.stderr)
            return 1
        print("index up to date")
        return 0

    INDEX.parent.mkdir(parents=True, exist_ok=True)
    INDEX.write_text(content)
    print(f"wrote {INDEX.relative_to(REPO)} ({len(discover())} docs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

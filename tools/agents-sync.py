#!/usr/bin/env python3
"""Propagate .agents/config/agent-rules.yaml into per-harness adapters.

Single source of truth:
    .agents/config/agent-rules.yaml   roles, model aliases, canary, MCP, commands
    .agents/roles/*.md                prompt bodies (no model IDs)
    .agents/commands/*.md             slash-command prompt bodies

Generated (do not hand-edit):
    .opencode/agent/<name>.md         opencode agent definitions
    .opencode/commands/<name>.md      opencode slash commands
    .opencode/opencode.json           opencode MCP + tool gating + provider models
    .mcp.json                         Claude-Code-compatible MCP config

Deterministic: same inputs produce byte-identical outputs, so `--check`
can be wired into CI to catch adapters that drifted from the config.

Usage:
    tools/agents-sync.py            write adapters
    tools/agents-sync.py --check    exit 1 if any adapter is stale
    tools/agents-sync.py --show     print resolved role/model bindings
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("PyYAML required: pip install pyyaml")

REPO = Path(__file__).resolve().parent.parent
CONFIG = REPO / ".agents/config/agent-rules.yaml"
ROLES = REPO / ".agents/roles"
COMMANDS = REPO / ".agents/commands"

BANNER = "GENERATED by tools/agents-sync.py from .agents/config/agent-rules.yaml — do not edit"


def load_config() -> dict:
    if not CONFIG.exists():
        sys.exit(f"missing {CONFIG.relative_to(REPO)}")
    return yaml.safe_load(CONFIG.read_text())


def resolve_canary(cfg: dict) -> str:
    """Stable per-checkout, distinct per machine, not runtime-derivable.

    Explicit config token wins. Otherwise hash $USER + repo path: the
    model cannot recompute this without already knowing the inputs and
    the construction, so emitting it is evidence it read the prompt.
    """
    canary = cfg.get("session", {}).get("canary", {})
    token = canary.get("token")
    if not token:
        prefix = canary.get("prefix", "AGENT-")
        seed = f"{os.environ.get('USER', 'unknown')}:{REPO}"
        token = prefix + hashlib.sha256(seed.encode()).hexdigest()[:6]
    return canary.get("format", "[{token}]").format(token=token)


def resolve_roles(cfg: dict, harness: str | None = None) -> dict:
    """Validate each role's alias. Concrete IDs are resolved per harness.

    A role may name the harnesses it applies to; omitting the key means
    all of them.
    """
    aliases = cfg["harness"]["aliases"]
    out = {}
    for role, spec in cfg["roles"].items():
        alias = spec["alias"]
        if alias not in aliases:
            sys.exit(f"role '{role}': unknown alias '{alias}'")
        only = spec.get("harnesses")
        if harness and only and harness not in only:
            continue
        out[role] = {**spec, "bare": aliases[alias]}
    return out


def model_for(cfg: dict, harness: str, spec: dict) -> tuple[str, str]:
    """(provider, model) for a role under a given harness.

    Providers are named differently per harness, so the binding lives in
    harness.targets rather than in the alias.
    """
    targets = cfg["harness"].get("targets", {})
    if harness not in targets:
        sys.exit(f"harness.targets missing entry for '{harness}'")
    t = targets[harness]
    bare = spec["bare"]
    return t["provider"], (t.get("rename") or {}).get(bare, bare)


def check_reasoning(cfg: dict, roles: dict) -> None:
    """Fail when a role's `reasoning:` is not a value its bound model accepts.

    Nothing upstream checks this, so a value the proxy rejects passes every config
    check there is and fails **at spawn time** — killing exactly the roles bound to
    that model and leaving the others working, which reads as a spawn flake rather
    than a config fault. The measured mechanism (opencode 1.18.32) is recorded
    **once**, in `agent-rules.yaml`'s `harness.reasoning_values` comment, and is
    deliberately not restated here: a derivation in two places is a derivation one
    of them will stop being true.

    A model with no `harness.reasoning_values` entry is an error too, not a
    pass: that is what forces an alias bump to declare the new model's accepted
    values, which is how `glm-5.3` rejecting `medium` would have been caught
    instead of discovered. The check keys on the id `model_for` resolves rather
    than the bare alias, so a `harness.targets.*.rename` entry cannot leave it
    validating a model that is never spawned; and a non-list or empty entry
    fails closed, because `value in "high"` is a substring test and a validator
    whose whole job is to refuse must have no shape under which it silently
    accepts.
    """
    accepted = cfg["harness"].get("reasoning_values") or {}
    targets = cfg["harness"].get("targets") or {}
    if not targets:
        sys.exit(
            "harness.targets is empty, so no role's model can be resolved and the "
            "reasoning check would silently validate nothing"
        )
    for role, spec in roles.items():
        value = spec.get("reasoning")
        if not value:
            continue
        only = spec.get("harnesses")
        checked = False
        for harness in targets:
            if only and harness not in only:
                continue
            checked = True
            model = model_for(cfg, harness, spec)[1]
            allowed = accepted.get(model)
            if allowed is None:
                sys.exit(
                    f"role '{role}': model '{model}' has no harness.reasoning_values "
                    f"entry, so `reasoning: {value}` cannot be validated. Add the "
                    f"values that model accepts — each row with its source — to "
                    f"agent-rules.yaml."
                )
            if not isinstance(allowed, list) or not allowed:
                sys.exit(
                    f"role '{role}': harness.reasoning_values['{model}'] must be a "
                    f"non-empty list, got {allowed!r}. A scalar would make the "
                    f"membership test a substring test, so `reasoning: {value}` "
                    f"cannot be validated against it."
                )
            if value not in allowed:
                sys.exit(
                    f"role '{role}': reasoning '{value}' is not accepted by "
                    f"'{model}' — this model takes: {', '.join(str(v) for v in allowed)}"
                )
        if not checked:
            sys.exit(
                f"role '{role}': its 'harnesses' filter {sorted(only)} matches no "
                f"entry in harness.targets, so `reasoning: {value}` was never validated"
            )


def report_contract(cfg: dict) -> str:
    """The subagent output contract, rendered once and shared verbatim."""
    rc = cfg["subagent_report"]
    rules = "\n".join(f"- {r}" for r in rc["rules"])
    return (
        f"## Output contract\n\n"
        f"Reply with **{rc['format'].upper()} only**, at most "
        f"{rc['max_lines']} lines. No prose outside it.\n\n"
        f"{rules}\n\n"
        f"```yaml\n{rc['schema'].rstrip()}\n```\n"
    )


def build_prompt(cfg: dict, role: str, spec: dict, canary: str, harness: str = "opencode") -> str:
    """Assemble an agent prompt: shared preamble first, then role body.

    The preamble is byte-identical across agents so the harness and
    provider can cache the longest possible common prefix. Role-specific
    text must never be hoisted into it.
    """
    parts = []
    for layer in spec.get("layers", ["_common"]):
        f = ROLES / f"{layer}.md"
        if not f.exists():
            sys.exit(f"role '{role}': missing layer {f.relative_to(REPO)}")
        parts.append(f.read_text().replace("{{CANARY}}", canary))

    if spec["mode"] == "subagent":
        parts.append(report_contract(cfg))

    body_file = "reviewer.md" if role.startswith("review") else f"{role}.md"
    body = (ROLES / body_file).read_text().replace("{{PURPOSE}}", spec.get("purpose", ""))
    if "{{DELEGATION}}" in body:
        d = ROLES / f"_delegation.{harness}.md"
        if not d.exists():
            sys.exit(f"missing {d.relative_to(REPO)}")
        body = body.replace("{{DELEGATION}}", d.read_text().strip())
    parts.append(body)
    return "\n".join(p.strip() + "\n" for p in parts)


def gen_opencode_agents(cfg: dict, roles: dict, canary: str) -> dict[Path, str]:
    """opencode markdown agents: frontmatter binds the model, body is the prompt."""
    files = {}
    for role, spec in roles.items():
        provider, model = model_for(cfg, "opencode", spec)
        fm = {
            "description": spec["purpose"],
            "mode": spec["mode"],
            "model": f"{provider}/{model}",
            "temperature": 0.1,
        }
        if spec.get("reasoning"):
            # Passed through to the provider as a model option.
            fm["reasoningEffort"] = spec["reasoning"]
        perm: dict[str, str] = {}
        if spec["mode"] == "subagent":
            # Reviewers must not edit; they return a verdict only.
            if role.startswith("review"):
                perm["edit"] = "deny"
            # Subagents may not spawn subagents: nested fan-out multiplies
            # cold caches and makes the loop unauditable.
            perm["task"] = "deny"

        # MCP gating lives here rather than in opencode.json so everything
        # about an agent is in one file. `permission` rather than the
        # deprecated `tools` map; opencode desugars `tools` into exactly
        # these rules anyway. Order matters — last match wins — so the
        # wildcard allow precedes the per-tool denies.
        for name, s in mcp_servers(cfg).items():
            if not s.get("enabled", True) or s.get("global", False):
                continue
            if spec["agent"] in (s.get("enable_for") or []):
                perm[f"{name}*"] = "allow"
                for tool in s.get("disable_tools", []):
                    perm[f"{name}_{tool}"] = "deny"

        # Per-role overrides go last: opencode resolves permissions with
        # last-match-wins, so this is the only position from which a role
        # can subtract from the wildcard allow above.
        perm.update(spec.get("permission") or {})
        if perm:
            fm["permission"] = perm

        lines = ["---"]
        lines.append(yaml.safe_dump(fm, sort_keys=False, default_flow_style=False).rstrip())
        lines.append("---")
        lines.append(f"<!-- {BANNER} -->")
        lines.append("")
        lines.append(build_prompt(cfg, role, spec, canary, "opencode").rstrip())
        lines.append("")
        files[REPO / f".opencode/agent/{spec['agent']}.md"] = "\n".join(lines)
    return files


def gen_opencode_commands(cfg: dict, roles: dict) -> dict[Path, str]:
    """opencode slash commands: `.opencode/commands/<name>.md`.

    The body lives in `.agents/commands/<name>.md` rather than inline in the
    YAML, because these templates embed shell injections and multi-paragraph
    instructions that YAML block scalars mangle (and that no editor
    syntax-highlights).

    `agent:` is validated against the resolved roles: a command pointing at
    an agent name that does not exist fails silently in the TUI, which is
    the single most annoying way for this to break.
    """
    files = {}
    agents = {spec["agent"] for spec in roles.values()}
    for name, spec in (cfg.get("commands") or {}).items():
        src = COMMANDS / f"{name}.md"
        if not src.exists():
            sys.exit(f"command '{name}': missing {src.relative_to(REPO)}")
        agent = spec.get("agent")
        if agent and agent not in agents:
            sys.exit(f"command '{name}': agent '{agent}' is not a configured role")

        fm: dict = {"description": spec["description"]}
        if agent:
            fm["agent"] = agent
        if "subtask" in spec:
            fm["subtask"] = spec["subtask"]
        if spec.get("alias"):
            provider, model = model_for(cfg, "opencode", {"bare": cfg["harness"]["aliases"][spec["alias"]]})
            fm["model"] = f"{provider}/{model}"

        lines = ["---"]
        lines.append(yaml.safe_dump(fm, sort_keys=False, default_flow_style=False).rstrip())
        lines.append("---")
        lines.append(f"<!-- {BANNER} -->")
        lines.append("")
        lines.append(src.read_text().strip())
        lines.append("")
        files[REPO / f".opencode/commands/{name}.md"] = "\n".join(lines)
    return files


def mcp_servers(cfg: dict) -> dict:
    return cfg.get("mcp", {}).get("servers", {}) or {}


def gen_opencode_json(cfg: dict) -> dict[Path, str]:
    """opencode config: MCP in opencode's own schema, plus tool gating."""
    conf: dict = {"$schema": "https://opencode.ai/config.json"}

    servers = mcp_servers(cfg)
    if servers:
        conf["mcp"] = {
            name: {
                "type": "local",
                "command": s["command"],
                "enabled": s.get("enabled", True),
                **({"environment": s["env"]} if s.get("env") else {}),
            }
            for name, s in servers.items()
        }
        # MCP tool schemas are injected into every request. Deny
        # non-global servers globally; agents re-allow in their own
        # front-matter (see gen_opencode_agents).
        denies = {
            f"{name}*": "deny"
            for name, s in servers.items()
            if not s.get("global", False)
        }
        if denies:
            conf["permission"] = denies

    # Hand-maintained opencode settings that have no place in the role
    # model (provider model declarations, tweaks to the built-in
    # build/plan agents). Merged last so the generator never silently
    # drops user configuration.
    for key, value in (cfg.get("harness", {}).get("opencode_passthrough") or {}).items():
        if isinstance(value, dict):
            conf.setdefault(key, {})
            for k, v in value.items():
                conf[key].setdefault(k, {}).update(v) if isinstance(v, dict) else conf[key].update({k: v})
        else:
            conf[key] = value

    return {REPO / ".opencode/opencode.json": json.dumps(conf, indent=2) + "\n"}


def gen_mcp_json(cfg: dict) -> dict[Path, str]:
    """Claude-Code-compatible harnesses read .mcp.json. stdio only."""
    servers = mcp_servers(cfg)
    if not servers:
        return {}
    out = {
        "mcpServers": {
            name: {
                "type": "stdio",
                "command": s["command"][0],
                "args": s["command"][1:],
                **({"env": s["env"]} if s.get("env") else {}),
            }
            for name, s in servers.items()
            if s.get("enabled", True)
        }
    }
    return {REPO / ".mcp.json": json.dumps(out, indent=2) + "\n"}


def write(files: dict[Path, str], check: bool) -> int:
    stale = []
    for path, content in sorted(files.items()):
        rel = path.relative_to(REPO)
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"{'updated' if current is not None else 'created'} {rel}")

    if check:
        if stale:
            print("stale adapters (run tools/agents-sync.py):", file=sys.stderr)
            for rel in stale:
                print(f"  {rel}", file=sys.stderr)
            return 1
        print("adapters up to date")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if adapters are stale")
    ap.add_argument("--show", action="store_true", help="print resolved bindings and exit")
    args = ap.parse_args()

    cfg = load_config()
    roles = resolve_roles(cfg)
    check_reasoning(cfg, roles)
    oc_roles = resolve_roles(cfg, "opencode")
    canary = resolve_canary(cfg)

    if args.show:
        print(f"canary: {canary}")
        for role, spec in roles.items():
            oc = "/".join(model_for(cfg, "opencode", spec))
            only = spec.get("harnesses")
            scope = f"  [{'+'.join(only)} only]" if only else ""
            print(f"  {role:18} {spec['agent']:26} {spec['alias']:6} "
                  f"opencode={oc}{scope}")
        for name, spec in (cfg.get("commands") or {}).items():
            print(f"  /{name:17} agent={spec.get('agent', '(current)')}")
        for name, s in mcp_servers(cfg).items():
            state = "enabled" if s.get("enabled", True) else "disabled"
            print(f"  mcp:{name:14} {state:9} {' '.join(s['command'])}")
        return 0

    files: dict[Path, str] = {}
    files |= gen_opencode_agents(cfg, oc_roles, canary)
    files |= gen_opencode_commands(cfg, oc_roles)
    files |= gen_opencode_json(cfg)
    files |= gen_mcp_json(cfg)
    return write(files, args.check)


if __name__ == "__main__":
    sys.exit(main())
